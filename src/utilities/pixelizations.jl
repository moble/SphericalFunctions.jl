@doc raw"""
    leja_pixels(s, ℓₘₐₓ, [T=Float64]; oversampling=2)

Choose [`Ysize(abs(s), ℓₘₐₓ)`](@ref Ysize) pixels — as many as there are modes of spin
weight `s` with ``|s| ≤ ℓ ≤ ℓₘₐₓ`` — so that the matrix of spin-weighted spherical harmonics
at those points is well conditioned.  This is needed to solve for the mode weights from
function values at exactly that many points.

The golden-ratio spiral of [`golden_ratio_spiral_pixels`](@ref) spreads its points evenly,
but that is not what such a solve needs, and with exactly as many points as modes the matrix
becomes badly conditioned as ℓₘₐₓ grows: its condition number is about ``10^4`` at ℓₘₐₓ =
16, ``10^5`` at 32 and ``10^{14}`` at 64.  The points chosen here are "discrete Leja points"
[BosEtAl_2010](@cite), which approximate the Fekete points that maximize the determinant of
the matrix: the harmonics are evaluated on a golden-ratio spiral of `oversampling` times as
many candidate points, and an LU decomposition with partial pivoting of that tall matrix
picks, one row at a time, the candidate that is least well represented by those already
picked.  With the default `oversampling=2`, the condition number is about 30 at ℓₘₐₓ = 16,
70–100 at 32 and 200–400 at 64, for either ``s = 0`` or ``s = 2``, and a round trip through
[`SSHTMatrix`](@ref) on these points loses about 3 digits at ℓₘₐₓ = 64 rather than all of
them.  (Up to ℓₘₐₓ ≈ 12 the two are comparable, with condition numbers of order 10, and the
spiral is sometimes slightly the better; beyond that it degrades and these points do not.)
Larger values of `oversampling`, which must be finite and at least 1, did not help
consistently in tests, and cost more.

The points depend on `s`, not just on their number, because the matrix does.  They are a
subset of that spiral, returned in its order (from the north pole to the south), and are
deterministic.  The candidates are chosen in `Float64`, by LAPACK's LU decomposition of the
harmonics at the `Float64` spiral, whatever `T` is, and only the chosen candidates are then
evaluated in `T`; so every `T` gets the same points, each rounded to `T`, and a function
sampled in one precision can be analysed in another.  The cost is that of the LU
decomposition of an ``N_c × N`` matrix, with ``N`` the number of modes and ``N_c`` the number
of candidates — about 2–3 times that of the decomposition [`SSHTMatrix`](@ref) itself
performs in `Float64`, or 2–3 seconds at ℓₘₐₓ = 64 — and its ``O(N^2)`` storage.  These are
the default sample points of [`SSHTMatrix`](@ref).

The spin weight and `ℓₘₐₓ` may be integers or half-odd-integers, as for
[`golden_ratio_spiral_pixels`](@ref), on the same terms.  The returned quantity is a vector
of 2-SVectors providing the spherical coordinates of each pixel.  See also
[`leja_rotors`](@ref) for the corresponding `Rotor`s.
"""
@index_methods function leja_pixels(
    s::IndexType, ℓₘₐₓ::IndexType, ::Type{T}=Float64; oversampling::Real=2
) where {T}
    check_band_limit(s, ℓₘₐₓ)
    if !(isfinite(oversampling) && oversampling ≥ 1)
        throw(ArgumentError(
            "oversampling=$oversampling must be at least 1, and finite, so that there are at "
            * "least as many candidates as points to choose."
        ))
    end
    N = Ysize(abs(s), ℓₘₐₓ)
    Nc = ceil(Int, oversampling * N)
    candidates = golden_ratio_spiral(Nc, Float64)
    # The rows of Y are the candidates; the first N row pivots are the points chosen.  With
    # `check=false` a numerically singular trailing block is not an error: the pivots are
    # chosen before it is reached.
    Y = sYlm_matrix(from_spherical_coordinates.(candidates), ℓₘₐₓ, s)
    F = LinearAlgebra.lu!(Y, LinearAlgebra.RowMaximum(); check=false)
    chosen = sort(F.p[1:N])
    T === Float64 ? candidates[chosen] : golden_ratio_spiral(Nc, T, chosen)
end

