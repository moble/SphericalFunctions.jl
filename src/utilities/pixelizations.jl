@doc raw"""
    sorted_rings(s, ℓₘₐₓ, [T=Float64])

Compute locations of a series of rings labelled by ``j ∈ |s|:ℓₘₐₓ`` (analogous to ``ℓ``).
Each ring will contain ``k = 2j+1`` (analogous to ``m``) pixels distributed evenly around
the ring.  These rings are then sorted, so that the ring with the most pixels (``j = ℓₘₐₓ``)
is closest to the equator, and the next-largest ring is placed just above or below the
equator (depending on the sign of ``s``), the next just below or above, and so on.  This is
generally a fairly good first guess when minimizing the condition number of matrices used to
solve for mode weights from function values, and for ``s = 0`` it gives the default rings of
the Minimal algorithm.  For ``s ≠ 0`` these rings are badly conditioned, and the Minimal
algorithm uses the different arrangement of [`minimal_rings`](@ref) instead; see
[`SSHTMinimal`](@ref).

The rings occupy the ``n = ℓₘₐₓ - |s| + 1`` interior points of an equally spaced grid on
``[0, π]``, and are assigned to them in order of size, from the slots farthest from the
equator to the nearest.  Two slots that are mirror images of each other across the equator
are equally far from it, and of the two rings assigned to such a pair, the larger goes to
the northern slot for ``s ≥ 0`` and to the southern for ``s < 0``.  The order is decided by
the positions of the slots in the grid, not by their rounded colatitudes, so it is the same
for every `T`, and for ``s ≠ 0`` the rings for ``-s`` are exactly the mirror images of those
for ``s``.  (For ``s = 0`` the larger ring of each mirror pair is the northern one, so the
rings are not symmetric about the equator.)

The spin weight and `ℓₘₐₓ` may be integers or half-odd-integers, the latter passed as
`Rational`s with denominator 2, as in `sorted_rings(1//2, 7//2)`; the two must be of one
kind.  There are then ``ℓₘₐₓ - |s| + 1`` rings, and ring ``j`` has ``2j+1`` pixels, both of
which are whole numbers for either kind of index.  A spin weight with ``|s| > ℓₘₐₓ``
describes no modes, and is an error.

This function does not provide the individual pixels; it just provides the colatitude values
of the rings on which the pixels will be placed.  The pixels themselves are provided by
[`sorted_ring_pixels`](@ref).
"""
@index_methods function sorted_rings(s::IndexType, ℓₘₐₓ::IndexType, ::Type{T}=Float64) where {T}
    check_band_limit(s, ℓₘₐₓ)
    n = ℓₘₐₓ - abs(s) + 1
    slots = collect(LinRange{T}(0, π, n + 2))[begin+1:end-1]
    slots[equatorward_order(n, s)]
end

# The order in which rings of increasing size fill `n` equally spaced slots, numbered from
# the north pole: from the slots farthest from the equator to the nearest.  The distance of
# slot i from the equator, in half slot spacings, is the integer |2i - (n+1)|, so the order
# is exact.  Mirror-image slots i and n+1-i are equally far from the equator, and the second
# ring of the two assigned to them, which is the larger, goes to the northern one for s ≥ 0
# and to the southern one for s < 0, so that the order for -s is the mirror image of that
# for s.
function equatorward_order(n::Int, s)
    north_last = s ≥ 0
    sort(1:n; by=i -> (-abs(2i - (n + 1)), north_last ? -i : i))
end


"""
    sorted_ring_pixels(s, ℓₘₐₓ, [T=Float64])

Cover the sphere 𝕊² with `Ysize(abs(s), ℓₘₐₓ)` pixels, distributed in the rings provided by
[`sorted_rings`](@ref).  That count is the number of modes of spin weight `s` with ``|s| ≤ ℓ
≤ ℓₘₐₓ``, which is ``(ℓₘₐₓ+1)²-s²``; see the documentation of [`sorted_rings`](@ref) for
more description, including the half-odd-integer values that `s` and `ℓₘₐₓ` may take.

The returned quantity is a vector of 2-SVectors containing the spherical coordinates of each
pixel.  See also [`sorted_ring_rotors`](@ref) for the corresponding `Rotor`s.
"""
@index_methods function sorted_ring_pixels(
    s::IndexType, ℓₘₐₓ::IndexType, ::Type{T}=Float64
) where {T}
    θrings = sorted_rings(s, ℓₘₐₓ, T)
    [
        @SVector [θ, ϕ]
        for (j,θ) ∈ zip(abs(s):ℓₘₐₓ, θrings)
        for ϕ ∈ LinRange{T}(0, 2T(π), 2j+2)[begin:end-1]
    ]
end

