# Pixelizations of the sphere.
#
# The golden-ratio spiral, the Leja points and the sorted rings are sized by the spin weight
# `s` and the band limit `ℓₘₐₓ`, which may be integers or half-odd-integers, the latter
# passed as `Rational`s with denominator 2 or as `HalfOddInteger`s.  Each of these functions
# is defined with `@index_methods`, so that its body sees two indices of one kind, `Int` or
# `HalfOddInteger`, and a call that mixes the kinds, or passes an index of another integer
# type, is refused with an explanation.  Every quantity the bodies form from the indices —
# the pixel count `Ysize(abs(s), ℓₘₐₓ)`, the number of rings ℓₘₐₓ - |s| + 1, and the 2j+1
# points on ring j — is an `Int` for either kind, so the bodies need no branch on the kind.
# A spin weight with |s| > ℓₘₐₓ describes no modes at all, and all of these functions refuse
# it with the same message before any point is placed.
#
# The point sets do not depend on the element type `T` in which they are returned, beyond
# the rounding of each coordinate: the golden-ratio spiral's colatitudes and azimuths are
# formed from exact integers, the Leja points are chosen in `Float64` whatever `T` is, and
# the rings are ordered by exact integer keys.  The Driscoll–Healy and McEwen–Wiaux grids
# further down are defined for integer indices only, and no transform defaults to them.

# Refuse a spin outside the band limit of ℓₘₐₓ; for integer indices this includes every
# negative ℓₘₐₓ.
function check_band_limit(s, ℓₘₐₓ)
    if abs(s) > ℓₘₐₓ
        throw(ArgumentError("|s|=$(abs(s)) exceeds ℓₘₐₓ=$ℓₘₐₓ; there are no such modes."))
    end
    nothing
end

@doc raw"""
    golden_ratio_spiral_pixels(s, ℓₘₐₓ, [T=Float64])

Cover the sphere 𝕊² with pixels generated by the golden-ratio spiral.  Successive pixels
are separated by the azimuthal angle ``Δϕ = 2π(2-φ)``, and are uniformly distributed in
``\cos θ``.

This is a common angular pattern of [phyllotaxis](https://en.wikipedia.org/wiki/Phyllotaxis)
in plants, found in sunflowers, pine cones, and artichokes, for example.  Wrapped around
𝕊², this is a very reasonable-looking pixelization, with fairly uniform distance between
neighbors, and approximate isotropy.  No two pixels will share the same values of either
``θ`` or ``ϕ``.  Also note that no point is present on either the North or South poles.

The number of pixels is [`Ysize(abs(s), ℓₘₐₓ)`](@ref Ysize), the number of modes of spin
weight `s` with ``|s| ≤ ℓ ≤ ℓₘₐₓ``, which is ``(ℓₘₐₓ+1)^2 - s^2`` for either kind of index.
The spin weight and `ℓₘₐₓ` may be integers or half-odd-integers, the latter passed as
`Rational`s with denominator 2, as in `golden_ratio_spiral_pixels(1//2, 7//2)`.  The two
must be of one kind; a call that mixes them, such as `golden_ratio_spiral_pixels(1//2, 3)`,
is an error, and so is a spin weight with ``|s| > ℓₘₐₓ``, for which there are no modes.

Pixel ``k = 0, 1, …, N-1`` of the ``N`` pixels has ``\cos θ = 1 - (2k+1)/N``, the center of
the ``k``th of ``N`` bands of equal width in ``\cos θ``, and so of equal area.  Its azimuth
is ``kΔϕ`` reduced modulo ``2π``, so that every ``ϕ`` lies in ``[0, 2π)``.  Both coordinates
are formed from exact integer quantities — the reduction modulo ``2π`` is made in exact
arithmetic — so that their only errors are those of the final few roundings, of about an ulp
of `T`, and the pixels in different types `T` are roundings of the same points.

This is also known as the "Fibonacci sphere" or "Fibonacci lattice" — though Fibonacci had
nothing to do with it; later authors pointed out relationships between his sequence and the
golden ratio.

The returned quantity is a vector of 2-SVectors providing the spherical coordinates of each
pixel.  See also [`golden_ratio_spiral_rotors`](@ref) for the corresponding `Rotor`s.

Note that these points can be constructed analytically, as is done here, but do not lead to
very well conditioned matrices of spin-weighted spherical harmonics.  A somewhat better
choice is given by [`leja_pixels`](@ref), which chooses a subset of the points of a denser
golden-ratio spiral with better conditioning, and is the default for [`SSHTMatrix`](@ref).
"""
@index_methods function golden_ratio_spiral_pixels(
    s::IndexType, ℓₘₐₓ::IndexType, ::Type{T}=Float64
) where {T}
    check_band_limit(s, ℓₘₐₓ)
    golden_ratio_spiral(Ysize(abs(s), ℓₘₐₓ), T)
end

# The spiral of any number `N` of points, which `leja_pixels` also uses, with more points
# than modes, as its set of candidates; or only the points of the spiral whose (1-based)
# positions are `indices`.
function golden_ratio_spiral(N::Int, ::Type{T}, indices=1:N) where {T}
    # Note: the formula used here looks different from some sources,
    # but just represents spiraling in the opposite direction.
    ϕ = golden_ratio_spiral_azimuths(indices .- 1, T)
    [@SVector [golden_ratio_spiral_colatitude(k, N, T), ϕₖ] for (k, ϕₖ) ∈ zip(indices, ϕ)]
end

# The colatitude of the point k = 1, …, N of the spiral.  The points are spaced uniformly in
# z = cos θ, at the centers z = 1 - (2k-1)/N of N bands of equal width 2/N, which by
# Archimedes' hat-box theorem are also bands of equal area.  Taking θ = acos(z) would be
# ill-conditioned near the poles, where the first and last points lie: dθ/dz = -1/sin θ, so
# the rounding error of z, about ε, becomes a relative error of about Nε/2 in the θ of the
# first point.  But both 1 - z = (2k-1)/N and 1 + z = (2N-2k+1)/N are exact ratios of
# integers, so N cos θ = N - 2k + 1 and N sin θ = N√((1-z)(1+z)) = √((2k-1)(2N-2k+1)) can be
# formed from integers, and the common factor N drops out of the two-argument arctangent,
# which is well conditioned for every θ in [0, π].  The only roundings are then those of the
# square root and the arctangent.  They are made in `Float64` for the smaller types, whose
# range could not hold the integers, and then rounded once to `T`.
function golden_ratio_spiral_colatitude(k::Int, N::Int, ::Type{T}) where {T}
    W = promote_type(T, Float64)
    T(atan(sqrt(W((2k-1)*(2N-2k+1))), W(N-2k+1)))
end

# The azimuths of the points k = 0, 1, … of the spiral, 2π times the fractional part of
# k(2-φ).  Formed as k times Δϕ = 2π(2-φ) in `T`, each would inherit the rounding error of
# Δϕ multiplied by k, which for the thousands of points of a spiral at moderate ℓₘₐₓ costs
# several digits of the azimuth in `Float32`, and makes the spirals of different types
# differ by more than their roundings.  So the fractional part is computed exactly, as k
# times a fixed-point approximation of 2-φ whose error, multiplied by k, stays far below the
# precision of `T`: with 128 bits for the types of at most 53 bits, whose azimuth is then
# formed as a double-length product in `Float64` and rounded once to `T`; and with 64 bits
# more than the precision of `T` for any other type, in `BigInt` arithmetic.
#
# 2 - φ = (3 - √5)/2, so its fixed-point approximation with P bits, the integer nearest to
# (2 - φ) 2ᴾ, follows from the integer square root of 5⋅4ᴾ.
golden_ratio_fraction(P) = (3 * big(2)^P - isqrt(5 * big(4)^P)) >> 1
const golden_ratio_fraction_128 = UInt128(golden_ratio_fraction(128))
const two_pi_hi = Float64(2big(π))
const two_pi_lo = Float64(2big(π) - two_pi_hi)

function golden_ratio_spiral_azimuths(
    ks, ::Type{T}
) where {T<:Union{Float16, Float32, Float64}}
    map(ks) do k
        # The fraction F/2¹²⁸ of a turn, split into its leading 53 bits, exactly, and the
        # rest, rounded; then 2π times that, with the error of the leading product recovered
        # by `fma`.  The product of `UInt128`s wraps around, which is reduction modulo 1.
        F = UInt128(k) * golden_ratio_fraction_128
        # `Float64` has 53 bits of precision.  We shift `F` by (128-53) = 75 bits to get the
        # leading 53 bits of `F` as a `Float64`, and multiply by 2⁻⁵³ to get the fraction of
        # a turn to `Float64` precision.
        hi = Float64(F >> 75) * 0x1p-53
        # Now we mask off the bits we just got, and multiply by 2⁻¹²⁸ to get the remaining
        # fraction of a turn, to the remaining precision available in the 128 bits of the
        # `UInt128`.
        lo = Float64(F & ((UInt128(1) << 75) - 1)) * 0x1p-128
        # The rest of this just preserves an ulp or two, but is fast and tested.
        p = two_pi_hi * hi
        e = fma(two_pi_hi, hi, -p)
        T(p + (e + fma(two_pi_hi, lo, two_pi_lo * hi)))
    end
end
function golden_ratio_spiral_azimuths(ks, ::Type{T}) where {T}
    P = 64 + (applicable(precision, T) ? precision(T) : precision(BigFloat))
    C = golden_ratio_fraction(P)
    one_turn = big(2)^P
    twoπ = 2T(π)
    map(k -> twoπ * T(BigFloat(mod(k * C, one_turn)) / BigFloat(one_turn)), ks)
end

