"""
    fejer1_rings(N, [T=Float64])

Values of the colatitude coordinate (``θ``) appropriate for quadrature by Fejér's first
rule, using weights provided by [`fejer1`](@ref).

Note that the first argument to this function is `N`, rather than the `ℓₘₐₓ` used in some
other functions.  For spin-weighted spherical harmonics, you may want to use `N=2ℓₘₐₓ+1`.
The number of rings `N` must be at least 1.
"""
function fejer1_rings(N, ::Type{T}=Float64) where T
    if N < 1
        throw(ArgumentError("`fejer1_rings` needs at least one ring; got N=$N."))
    end
    # Eq. (12) of Reinecke and Seljebotn
    let π = T(π)
        [(2n+1)*π/2N for n ∈ 0:N-1]
    end
end

"""
    fejer2_rings(N, [T=Float64])

Values of the colatitude coordinate (``θ``) appropriate for quadrature by Fejér's second
rule, using weights provided by [`fejer2`](@ref).

Note that the first argument to this function is `N`, rather than the `ℓₘₐₓ` used in some
other functions.  For spin-weighted spherical harmonics, you may want to use `N=2ℓₘₐₓ+1`.
The number of rings `N` must be at least 1.
"""
function fejer2_rings(N, ::Type{T}=Float64) where T
    if N < 1
        throw(ArgumentError("`fejer2_rings` needs at least one ring; got N=$N."))
    end
    # Eq. (13) of Reinecke and Seljebotn, with N adjusted to reflect actual number of elements
    let π = T(π)
        [n*π/(N+1) for n ∈ 1:N]
    end
end

"""
    clenshaw_curtis_rings(N, [T=Float64])

Values of the colatitude coordinate (``θ``) appropriate for quadrature by the
Clenshaw-Curtis rule, using weights provided by [`clenshaw_curtis`](@ref).

Note that the first argument to this function is `N`, rather than the `ℓₘₐₓ` used in some
other functions.  For spin-weighted spherical harmonics, you may want to use `N=2ℓₘₐₓ+1`.
The number of rings `N` must be at least 2, since the rings include both poles.
"""
function clenshaw_curtis_rings(N, ::Type{T}=Float64) where T
    if N < 2
        throw(ArgumentError(
            "`clenshaw_curtis_rings` needs at least two rings, one at each pole; got N=$N."
        ))
    end
    # Eq. (14) of Reinecke and Seljebotn, with N adjusted to reflect actual number of elements
    let π = T(π)
        [n*π/(N-1) for n ∈ 0:N-1]
    end
end

# The two equiangular grids below are defined for integer indices only, which
# `@index_methods integer_only` enforces for the spin weight as well as the band limit,
# although neither grid uses the spin weight.  A half-integer call is told which
# pixelizations to use instead.  What is left to check is the sign of the band limit.
function check_equiangular_band_limit(grid, ℓₘₐₓ)
    if ℓₘₐₓ < 0
        throw(ArgumentError("The $grid grid needs a non-negative band limit; got ℓₘₐₓ=$ℓₘₐₓ."))
    end
    nothing
end

@doc raw"""
    driscoll_healy_pixels([s], ℓₘₐₓ, [T=Float64])

Cover the sphere 𝕊² with pixels given by the [DriscollHealy_1994](@citet) equiangular grid.
They write:

> Let ``f(θ, ϕ)`` be a band-limited function such that ``\hat{f}(l, m) = 0`` for ``l ≥ b``.
> We sample the function at the equiangular grid of points ``(θ_i, ϕ_j)``, ``i = 0, \ldots,
> 2b-1``, ``j = 0, \ldots, 2b-1``, where ``θ_i = π i/2b`` and ``ϕ_j = π j/b``.

The band limit here is ``b = ℓₘₐₓ + 1``, and `ℓₘₐₓ` must be a non-negative integer.  The
grid is defined for integer indices only; functions of half-integer spin are sampled with
[`golden_ratio_spiral_pixels`](@ref), [`leja_pixels`](@ref) or [`sorted_ring_pixels`](@ref)
instead.

These are the ``(2b)^2`` points returned, ordered with ``ϕ`` varying fastest.  The first
ring, ``i = 0``, lies at the north pole ``θ = 0``, and all ``2b`` of its points are
included, as distinct rotors that differ by a rotation about the pole.  The grid does not
reach the south pole, since the largest colatitude is ``π(2b-1)/2b``.

The returned quantity is a vector of 2-SVectors providing the spherical coordinates of each
pixel.  See also [`driscoll_healy_rotors`](@ref) for the corresponding `Rotor`s.

!!! note
    The `s` argument is not used in this function, but is included for consistency with
    other pixelization functions.  It must be an integer, like `ℓₘₐₓ`.
"""
@index_methods integer_only (
    "Functions of half-integer spin may be sampled with `golden_ratio_spiral_pixels`, "
    * "`leja_pixels` or `sorted_ring_pixels`."
) function driscoll_healy_pixels(s::IndexType, ℓₘₐₓ::IndexType, ::Type{T}=Float64) where {T}
