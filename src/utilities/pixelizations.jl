@doc raw"""
    mcewen_wiaux_pixels([s], ℓₘₐₓ, [T=Float64])

Cover the sphere 𝕊² with pixels given by the [McEwenWiaux_2011](@citet) equiangular grid.
They consider "signals on the sphere bandlimited at ``L``, that is signals such that
``{}_sf_{ℓm} = 0, ∀ℓ ≥ L``", so that ``L = ℓₘₐₓ + 1`` here, and write:

> We adopt an equiangular sampling of the sphere with sample positions given by ``θ_t =
> \frac{π(2t+1)}{2L-1}``, where ``t ∈ \{0, 1, …, L-1\}`` […] and ``ϕ_p = \frac{2πp}{2L-1}``,
> where ``p ∈ \{0, 1, …, 2L-2\}``.

The band limit `ℓₘₐₓ` must be a non-negative integer.  The grid is defined for integer
indices only; functions of half-integer spin are sampled with
[`golden_ratio_spiral_pixels`](@ref), [`leja_pixels`](@ref) or [`sorted_ring_pixels`](@ref)
instead.

These are the ``L(2L-1)`` points returned, ordered with ``ϕ`` varying fastest.  The last
ring, ``t = L-1``, lies at the south pole ``θ = π``, and all ``2L-1`` of its points are
included, as distinct rotors that differ by a rotation about the pole; McEwen and Wiaux
count the pole once, for ``(L-1)(2L-1)+1`` samples.  Their algorithm also extends the ``θ``
domain to ``[0, 2π)``, reflecting the samples through the south pole to ``t ∈ \{L, …,
2L-2\}``, but those are not further sample positions on the sphere, and are not returned.

!!! note
    The `s` argument is not used in this function, but is included for consistency with
    other pixelization functions.  It must be an integer, like `ℓₘₐₓ`.
"""
@index_methods integer_only (
    "Functions of half-integer spin may be sampled with `golden_ratio_spiral_pixels`, "
    * "`leja_pixels` or `sorted_ring_pixels`."
) function mcewen_wiaux_pixels(s::IndexType, ℓₘₐₓ::IndexType, ::Type{T}=Float64) where {T}
    check_equiangular_band_limit("McEwen–Wiaux", ℓₘₐₓ)
    let π = T(π), L = ℓₘₐₓ + 1
        # The ratio is formed first, so that it is exactly 1 on the last ring, which is then
        # exactly at the south pole rather than an ulp to either side of it.
        [
            @SVector [π * (T(2t+1) / T(2L - 1)), 2π*p / (2L - 1)]
            for t ∈ 0:(L - 1)
            for p ∈ 0:(2L - 2)
        ]
    end
end
@index_methods integer_only (
    "Functions of half-integer spin may be sampled with `golden_ratio_spiral_pixels`, "
    * "`leja_pixels` or `sorted_ring_pixels`."
) mcewen_wiaux_pixels(ℓₘₐₓ::IndexType, ::Type{T}=Float64) where {T} =
    mcewen_wiaux_pixels(0, ℓₘₐₓ, T)

